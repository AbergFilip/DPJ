// Flera språk i plockappen. Lagret har personal med olika förstaspråk, så varje person kan välja sitt.
// Översikten för arbetsledaren är kvar på svenska. Texten byts genom att sidan laddas om, så inget
// pågående plock påverkas (allt ligger i databasen eller i mobilens kö).
export type Lang = "sv" | "en" | "pl" | "ar"
export const LANGS: { code: Lang; name: string; short: string }[] = [
  { code: "sv", name: "Svenska", short: "SV" },
  { code: "en", name: "English", short: "EN" },
  { code: "pl", name: "Polski", short: "PL" },
  { code: "ar", name: "العربية", short: "AR" },
]
const RTL: Lang[] = ["ar"]
const KEY = "dpj-plock-lang"

export function getLang(): Lang {
  try { const v = localStorage.getItem(KEY) as Lang | null; if (v && LANGS.some(l => l.code === v)) return v } catch { /* privat läge */ }
  const nav = navigator.language.slice(0, 2)
  return (LANGS.find(l => l.code === nav)?.code ?? "sv") as Lang
}
export const isRtl = (l: Lang = lang) => RTL.includes(l)

export function setLang(l: Lang) {
  try { localStorage.setItem(KEY, l) } catch { /* privat läge */ }
  location.reload()
}

export const lang = getLang()
export function applyLang() {
  document.documentElement.lang = lang
  document.documentElement.dir = isRtl() ? "rtl" : "ltr"
}

// {namn} i texten byts mot värdet. Saknas översättningen används svenskan.
export function t(key: string, vars?: Record<string, string | number>): string {
  const row = DICT[key]
  const i = LANGS.findIndex(l => l.code === lang)
  let s = (row && (row[i] || row[0])) ?? String(key)
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
  return s
}

